export function searchTacoDatabase(query: string, limit: number = 20): TacoFoodItem[] {
  if (!query || !query.trim()) {
    return TACO_DATABASE.slice(0, limit);
  }

  const clean = query.trim().toLowerCase();
  const words = clean.split(/\s+/).filter(Boolean);

  const scored = TACO_DATABASE.map((item) => {
    const itemName = item.name.toLowerCase();
    const itemCat = item.category.toLowerCase();
    let score = 0;

    if (itemName === clean) score += 100;
    else if (itemName.startsWith(clean)) score += 50;
    else if (itemName.includes(clean)) score += 30;

    for (const w of words) {
      if (itemName.includes(w)) score += 15;
      if (itemCat.includes(w)) score += 5;
    }

    return { item, score };
  });

  return scored
    .filter((s) => s.score > 0)
    .sort((a, b) => b.score - a.score)
    .map((s) => s.item)
    .slice(0, limit);
}
